#!/usr/bin/env python3
"""Generate ANSI Lisp NFC tables from Python UCD 15.1.0; offline, no runtime dependency.
UAX #15: canonical decomposition, combining class, non-excluded composition pairs.
Hangul decomposition/composition is algorithmic. Generated output is committed.
"""
import pathlib
import unicodedata as u
assert u.unidata_version == '15.1.0', u.unidata_version
out = [';;;; Generated by scripts/generate-nfc-data.py; Unicode 15.1.0.',
       '(in-package #:topic-maps.cxtm)']
def table(name, rows):
    out.append(f'(defparameter {name} (let ((h (make-hash-table :test #\'eql)))')
    out.append("  (dolist (entry '(")
    out.extend('    (' + ' '.join(map(str, row)) + ')' for row in rows)
    out.append('    )) (setf (gethash (first entry) h) (rest entry))) h))')
decomp=[]; ccc=[]; compose=[]
for n in range(0x110000):
    c=chr(n); d=u.decomposition(c)
    if d and not d.startswith('<'):
        seq=[int(x,16) for x in d.split()]; decomp.append([n,*seq])
        if len(seq)==2 and u.normalize('NFC',''.join(map(chr,seq)))==c:
            compose.append([seq[0]*0x110000+seq[1],n])
    if u.combining(c): ccc.append([n,u.combining(c)])
table('*decompositions*',decomp); table('*combining-classes*',ccc); table('*compositions*',compose)
ranges=[]; start=None
for n in range(0x110001):
    assigned=n < 0x110000 and u.category(chr(n)) != 'Cn'
    if assigned and start is None: start=n
    if not assigned and start is not None: ranges.extend([start,n-1]); start=None
out.append('(defparameter *assigned-ranges* #(' + ' '.join(map(str,ranges)) + '))')
pathlib.Path(__file__).resolve().parents[1].joinpath('src/cxtm/nfc-data.lisp').write_text('\n'.join(out)+'\n')
print('UCD 15.1.0:', len(decomp),'decompositions,',len(ccc),'combining classes,',len(compose),'composition pairs')
